# Pega uma lista de valores
# (por exemplo, os valores de um critério, os valores de uma coluna)
# e gera outra lista representando os valores de uma matriz de julgamentos
def julgamentos_alternativa(normalized_values, inverse):
  combinations_list = []
  if (inverse):
    for i, j in itertools.combinations(range(len(normalized_values)), 2):
      combinations_list.append(normalized_values[j] / normalized_values[i])
  else:
    for i, j in itertools.combinations(range(len(normalized_values)), 2):
      combinations_list.append(normalized_values[i] / normalized_values[j])
  return combinations_list

# Arredonda os valores da lista que representa os valores da matriz de julgamentos
# gerados pela função 'julgamentos_alternativa'
# O arredondamento reflete a escala Saaty
def arredonda_lista(lista,referencia):
  lista_arredondado = []
  for valor in lista:
    if valor >= 1:
      lista_arredondado.append(round(valor))
    else:
      diferenca_minima = float('inf')
      divisor_proximo = 0
      for divisor in referencia:
        diferenca = abs(valor - divisor)
        if diferenca < diferenca_minima:
          diferenca_minima = diferenca
          divisor_proximo = divisor
      lista_arredondado.append(divisor_proximo)
  return lista_arredondado

# Gera o dicionario dos julgamentos , utilizando uma lista das alternativas ou critérios
def gera_dicionario_julgamentos(chave, julgamentos):
  chave_pares = list(itertools.combinations(chave, 2))
  dic_julgamentos = dict(zip(chave_pares, julgamentos))
  return dic_julgamentos

