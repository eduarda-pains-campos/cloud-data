# Encontra os pares de alternativas onde não existe julgamento (valor 0)
# e remove estes pares
# Obs: O algoritmo da Biblioteca consegue lidar com pares faltantes
def remove_zero_values(dictionary):
    keys_to_remove = [key for key, value in dictionary.items() if value == 0]
    for key in keys_to_remove:
        del dictionary[key]

# Encontra os pares de alternativas onde não existe julgamento (valor 0)
# e substitui por um julgamento equivalente (valor 1)
def replace_zero_values(dictionary):
    for key, value in dictionary.items():
        if value == 0:
            dictionary[key] = 1

def normalize_dict(data_dict):
  min_value = min(data_dict.values())
  max_value = max(data_dict.values())

  normalized_dict = {k: (v - min_value) / (max_value - min_value) for k, v in data_dict.items()}
  return normalized_dict

