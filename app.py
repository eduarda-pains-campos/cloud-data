# Adiciona um valor muito baixo (epsilon) em valores que possuem zero
def tratamento_zeros1(df):
  epsilon = 0.0001

  # Percorrendo cada coluna
  for column in df.columns:
      # Apenas colunas numéricas (sem string, objeto)
      if df[column].dtype != object:
          # Retorna uma serie informando quais linhas, a coluna 'column' possui zero
          zeros_mask = (df[column] == 0)
          # Verifica se tem algum valor zero e adiciona o epsilon
          if zeros_mask.any():
              df.loc[zeros_mask, column] += epsilon

# Adiciona um valor muito baixo (epsilon) para todas as colunas
def tratamento_zeros2(df):
  epsilon = 0.0001
  for column in df.columns:
    if df[column].dtype != object:
      df[column] += epsilon

# Normaliza valores entre 1 e 9 (julgamentos de Saaty)
def normalize(values):
  min_val = min(values)
  max_val = max(values)
  normalized_values = []
  for val in values:
    normalized_val = ((val - min_val) / (max_val - min_val)) * 8 + 1
    normalized_values.append(normalized_val)
  return normalized_values

